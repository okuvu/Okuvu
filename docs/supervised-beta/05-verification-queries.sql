-- =============================================================================
-- E13-S03 Supervised Beta — Acceptance verification
-- Run against evia-beta (project evia-500215, Neon) at the end of the beta:
--     psql "DATABASE_URL" -f docs/supervised-beta/05-verification-queries.sql
--
-- EDIT THIS ONE PARAMETER before running:
--   beta_start = first day of the supervised beta period (IST).
-- =============================================================================
\set beta_start '2026-09-01'

-- -----------------------------------------------------------------------------
-- 1. Total real beta sessions (ACCEPTANCE: >= 15).
-- A "real session" = turn_count > 0 for a client with a TherapistClient pairing.
-- This is the beta flag: no schema column exists; being in a therapist-client
-- pair marks the session as supervised-beta (not dogfooding).
-- -----------------------------------------------------------------------------
SELECT COUNT(*) AS beta_session_count
FROM "SessionLog" sl
JOIN "TherapistClient" tc ON tc.client_user_id = sl.user_id
WHERE sl.turn_count > 0
  AND sl.session_started_at >= DATE :beta_start;

-- -----------------------------------------------------------------------------
-- 2. Sessions per therapist-client pair (planning / debugging view).
-- -----------------------------------------------------------------------------
SELECT t.email                              AS therapist_email,
       u.id                                 AS client_user_id,
       u.phone_number,
       COUNT(sl.id) FILTER (
           WHERE sl.turn_count > 0
             AND sl.session_started_at >= DATE :beta_start
       )                                    AS session_count
FROM "TherapistClient" tc
JOIN "Therapist" t        ON t.id = tc.therapist_id
JOIN "User" u             ON u.id = tc.client_user_id
LEFT JOIN "SessionLog" sl ON sl.user_id = tc.client_user_id
GROUP BY t.email, u.id, u.phone_number
ORDER BY session_count DESC;

-- -----------------------------------------------------------------------------
-- 3. T-03 validated change (ACCEPTANCE: >= 1 confirmed row).
-- assignment_state is only set to 'confirmed' by a therapist T-03 save;
-- A2 onboarding always creates 'provisional' (see packages/prisma/seed.ts).
-- -----------------------------------------------------------------------------
SELECT u.id AS client_user_id,
       u.phone_number,
       cc.care_plan_id,
       cc.assignment_state
FROM "ClinicalConfig" cc
JOIN "TherapistClient" tc ON tc.client_user_id = cc.user_id
JOIN "User" u             ON u.id = cc.user_id
WHERE cc.assignment_state = 'confirmed';

-- -----------------------------------------------------------------------------
-- 4. T-05 real session note (ACCEPTANCE: >= 1 note for a paired client).
-- -----------------------------------------------------------------------------
SELECT t.email,
       COUNT(n.id) AS note_count
FROM "TherapistNote" n
JOIN "Therapist" t        ON t.id = n.therapist_id
JOIN "TherapistClient" tc ON tc.client_user_id = n.client_user_id
                         AND tc.therapist_id = n.therapist_id
WHERE n.created_at >= DATE :beta_start
GROUP BY t.email;

-- -----------------------------------------------------------------------------
-- 5. Session summaries auto-generated by E7-S03 on beta sessions.
-- -----------------------------------------------------------------------------
SELECT ss.status,
       COUNT(*) AS summary_count
FROM "SessionSummary" ss
JOIN "TherapistClient" tc ON tc.client_user_id = ss.user_id
WHERE ss.created_at >= DATE :beta_start
GROUP BY ss.status
ORDER BY summary_count DESC;