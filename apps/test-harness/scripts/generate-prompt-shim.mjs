// Regenerates a webpack-resolvable shim for apps/api/src/prompts/index.ts's
// prompt constants, run before every dev/build (see package.json).
//
// WHY THIS EXISTS: apps/api/src/prompts/index.ts reads this .txt file via
// readFileSync(join(__dirname, ...)) at module load time. That's the right
// approach for apps/api's own deployment (a Docker container with the whole
// repo on disk), but on Vercel — where this app's Root Directory is
// apps/test-harness — the deployed function's packaging step doesn't
// reliably include files living outside that directory (confirmed live:
// ENOENT even after outputFileTracingIncludes/outputFileTracingRoot, both
// of which resolve correctly in a local build). Every procedure that
// imports the orchestrator (i.e. all of them) crashes at module load as a
// result.
//
// FIX: generate a small shim exporting the exact same constants as plain
// string literals, and alias apps/api/src/prompts/index.ts to it in
// next.config.ts's webpack config (test-harness's build only — apps/api's
// own Docker/tsc build is completely untouched). Regenerating from the
// live .txt file on every build (rather than a committed, hand-copied
// duplicate) means this can never silently drift from the real prompt
// content, including through Stage 2 clinical review revisions.
//
// Output is gitignored — it's a build artifact, not source.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const promptsDir = join(__dirname, '..', '..', 'api', 'src', 'prompts');
const outDir = join(__dirname, '..', '.generated');
const outFile = join(outDir, 'prompt-shim.ts');

const mvp = readFileSync(join(promptsDir, 'a2-okuvu-v2.1.txt'), 'utf-8');

// A2_PROMPT_VERSION is a plain string literal in the real
// apps/api/src/prompts/index.ts (no file I/O involved, unlike the
// prompt body above), so there's nothing to read from disk here — but
// since next.config.ts's webpack alias replaces that ENTIRE module with
// this shim, every export it has must be mirrored here too, or any caller
// bundled through test-harness's webpack build gets an
// "is not exported" error at runtime despite `tsc`/`vitest` passing clean
// (confirmed live 2026-09-06 — see docs/test-harness/mvp-v2-engineering-spec.md's
// implementation-status note). Kept in sync by hand, same as
// apps/api/src/prompts/index.ts's own comment already says about this value.
const promptVersion = 'v2.1';

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-prompt-shim.mjs — do not edit.\n` +
    `// Regenerated from apps/api/src/prompts/*.txt on every dev/build.\n\n` +
    `export const A2_PROMPT = ${JSON.stringify(mvp)};\n\n` +
    `export const A2_PROMPT_VERSION = ${JSON.stringify(promptVersion)};\n`,
  'utf-8',
);

console.log(`[generate-prompt-shim] wrote ${outFile}`);
