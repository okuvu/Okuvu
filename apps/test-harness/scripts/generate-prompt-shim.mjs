// Regenerates a webpack-resolvable shim for apps/api/src/prompts/index.ts's
// prompt constants, run before every dev/build (see package.json).
//
// WHY THIS EXISTS: apps/api/src/prompts/index.ts reads a .txt file via
// readFileSync(join(__dirname, ...)) at module load time. That's the right
// approach for apps/api's own deployment (a Docker container with the whole
// repo on disk), but on Vercel — where this app's Root Directory is
// apps/test-harness — the deployed function's packaging step doesn't
// reliably include files living outside that directory (confirmed live:
// ENOENT even after outputFileTracingIncludes/outputFileTracingRoot, both
// of which resolve correctly in a local build). Every procedure that
// imports the orchestrator (i.e. all of them) crashes at module load as a
// result.
//
// FIX: generate a small shim exporting the exact same constants as plain
// string literals, and alias apps/api/src/prompts/index.ts to it in
// next.config.ts's webpack config (test-harness's build only — apps/api's
// own Docker/tsc build is completely untouched). Regenerating from the
// live module on every build (rather than a committed, hand-copied
// duplicate) means this can never silently drift from the real prompt
// content, including through Stage 2 clinical review revisions.
//
// Output is gitignored — it's a build artifact, not source.
//
// IT IMPORTS THE MODULE, IT DOES NOT PARSE IT. This script used to regex
// `A2_PROMPT_VERSION = '<literal>'` and a literal `.txt` filename out of
// index.ts. When the strict prompt gate made the default a decision,
// index.ts became `A2_PROMPT_VERSION = defaultPromptVersion()` with a
// template-built filename — no literals left — and this script refused to
// emit a shim at all, so predev/prebuild failed before the harness app ever
// started. Importing the module asks the api itself for the two values it
// exports, which is the only source that cannot disagree with what
// production sends. Run with `tsx` (see package.json) because that module
// is TypeScript.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { A2_PROMPT, A2_PROMPT_VERSION } from '../../api/src/prompts/index.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = join(__dirname, '..', '.generated');
const outFile = join(outDir, 'prompt-shim.ts');

// Fail closed on a shape that would make the shim useless, rather than writing
// an empty prompt and letting every procedure serve nothing.
if (typeof A2_PROMPT !== 'string' || A2_PROMPT.trim() === '') {
  console.error('[generate-prompt-shim] the api exported an empty A2_PROMPT. Refusing to emit a shim.');
  process.exit(1);
}
if (typeof A2_PROMPT_VERSION !== 'string' || !/^v\d+\.\d+$/.test(A2_PROMPT_VERSION)) {
  console.error(
    `[generate-prompt-shim] the api exported A2_PROMPT_VERSION=${JSON.stringify(A2_PROMPT_VERSION)}, ` +
      'which is not a version string. Refusing to emit a shim.',
  );
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-prompt-shim.mjs — do not edit.\n` +
    `// Regenerated from apps/api/src/prompts/index.ts on every dev/build.\n\n` +
    `export const A2_PROMPT = ${JSON.stringify(A2_PROMPT)};\n\n` +
    `export const A2_PROMPT_VERSION = ${JSON.stringify(A2_PROMPT_VERSION)};\n`,
  'utf-8',
);

console.log(`[generate-prompt-shim] wrote ${outFile} (${A2_PROMPT_VERSION})`);
